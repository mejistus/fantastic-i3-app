    /// 把这条放回剪贴板；paste 时关掉面板后按一下 ⌘V（面板没抢前台，粘到原来的应用里）
    func confirm(_ row: Int, paste: Bool = true) {
        guard shown.indices.contains(row) else { return }
        let entry = shown[row].entry
        // 用过的那条挪到最前面，日期也算现在（保留期从最近一次用起算）。记录的那个进程重读一次
        if let index = all.firstIndex(where: { $0.entry.id == entry.id }) {
            var used = all.remove(at: index)
            used.entry.date = Date()
            all.insert(used, at: 0)
            saveClipHistory(all.map(\.entry))
            let reload = Process()
            reload.executableURL = URL(fileURLWithPath: "/usr/bin/pkill")
            reload.arguments = ["-HUP", "-f", "^\(CommandLine.arguments[0]) clipboard-watch"]
            try? reload.run()
        }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.kind {
        case "image":
            if let name = entry.image, let image = NSImage(contentsOfFile: clipboardImages + "/" + name) {
                pasteboard.writeObjects([image])
            }
        case "files":
            let urls = (entry.text ?? "").split(separator: "\n").map { NSURL(fileURLWithPath: String($0)) }
            pasteboard.writeObjects(urls)
        default:
            pasteboard.setString(entry.text ?? "", forType: .string)
        }
        panel.orderOut(nil)
        guard paste else { exit(0) }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) {
            let source = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: down)   // V
                event?.flags = .maskCommand
                event?.post(tap: .cghidEventTap)
            }
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.1) { exit(0) }
        }
    }

    func deleteSelected() {
        let row = table.selectedRow
        guard shown.indices.contains(row) else { return }
        let id = shown[row].entry.id
        all.removeAll { $0.entry.id == id }
        shown.remove(at: row)
        saveClipHistory(all.map(\.entry))
        let reload = Process()   // 让记录的那个重读
        reload.executableURL = URL(fileURLWithPath: "/usr/bin/pkill")
        reload.arguments = ["-HUP", "-f", "^\(CommandLine.arguments[0]) clipboard-watch"]
        try? reload.run()
        table.reloadData()
        select(min(row, shown.count - 1))
        if shown.isEmpty { showPreview(nil) }
    }

