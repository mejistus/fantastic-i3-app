    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let entry = shown[row].entry
        let cell = NSTableCellView()
        let width = tableColumn?.width ?? scroll.contentSize.width
        let rowHeight = table.rowHeight
        let iconSize = round(28 * scale)
        let icon = NSImageView(frame: NSRect(x: round(10 * scale), y: (rowHeight - iconSize) / 2, width: iconSize, height: iconSize))
        icon.imageScaling = .scaleProportionallyUpOrDown
        if let thumbnail = rowThumbnail(entry) {
            icon.image = thumbnail
        } else if entry.kind == "image" {
            icon.image = NSImage(systemSymbolName: "photo", accessibilityDescription: nil)
        } else if entry.kind == "files", let first = filePaths(entry).first {
            icon.image = NSWorkspace.shared.icon(forFile: first)
        } else {
            icon.image = appIcon(entry.bundle) ?? NSImage(systemSymbolName: "doc.text", accessibilityDescription: nil)
        }
        cell.addSubview(icon)

        let titleFont = NSFont.systemFont(ofSize: fontSize, weight: .medium)
        let title = NSTextField(labelWithString: "")
        title.attributedStringValue = highlighted(shown[row].title.isEmpty ? " " : shown[row].title, font: titleFont)
        title.lineBreakMode = .byTruncatingTail
        title.maximumNumberOfLines = 1
        let detail = NSTextField(labelWithString: [entry.app, timeText(entry.date)].compactMap { $0 }.joined(separator: " · "))
        detail.font = .systemFont(ofSize: max(9, round(11 * scale)))
        detail.textColor = .secondaryLabelColor
        detail.lineBreakMode = .byTruncatingTail
        // 两行字作为一块，在行里竖直居中
        let titleHeight = ceil(title.intrinsicContentSize.height), detailHeight = ceil(detail.intrinsicContentSize.height)
        let bottom = ((rowHeight - titleHeight - detailHeight) / 2).rounded()
        let x = icon.frame.maxX + round(10 * scale)
        title.frame = NSRect(x: x, y: bottom + detailHeight, width: width - x - 10, height: titleHeight)
        detail.frame = NSRect(x: x, y: bottom, width: width - x - 10, height: detailHeight)
        cell.addSubview(title)
        cell.addSubview(detail)
        return cell
    }

    /// 列表标题里把搜索命中的字符标出来：模糊匹配标实际对上的那几个字（和打分的对齐是同一份），
    /// 正则标每段匹配。看不清哪条为什么排上来时，看高亮就知道
    func highlighted(_ text: String, font: NSFont) -> NSAttributedString {
        let attributed = NSMutableAttributedString(string: text, attributes: [
            .font: font, .foregroundColor: NSColor.labelColor,
        ])
        for range in highlightRanges(in: text) where range.length > 0 && range.location + range.length <= attributed.length {
            attributed.addAttribute(.backgroundColor, value: NSColor.controlAccentColor.withAlphaComponent(0.30), range: range)
        }
        return attributed
    }

    func highlightRanges(in text: String) -> [NSRange] {
        guard !activeQuery.isEmpty else { return [] }
        if activeQuery.hasPrefix("/") {
            let pattern = String(activeQuery.dropFirst())
            guard !pattern.isEmpty, let regex = try? NSRegularExpression(pattern: pattern, options: [.caseInsensitive])
            else { return [] }
            return regex.matches(in: text, range: NSRange(text.startIndex..., in: text)).map(\.range)
        }
        let lower = Array(text.lowercased())
        var ranges: [NSRange] = []
        for term in activeQuery.split(separator: " ") {
            guard let match = substringMatch(queryTerm(String(term)), lower) else { continue }
            ranges += utf16Ranges(match.positions, in: text)
        }
        return ranges
    }

    /// 预览里的高亮：每一处出现都标（列表里只标打分选中的那一处，正文太长时后面的命中看不到）
    func allHighlightRanges(in text: String) -> [NSRange] {
        guard !activeQuery.isEmpty else { return [] }
        if activeQuery.hasPrefix("/") {
            let pattern = String(activeQuery.dropFirst())
            guard !pattern.isEmpty, let regex = try? NSRegularExpression(pattern: pattern, options: [.caseInsensitive])
            else { return [] }
            return regex.matches(in: text, range: NSRange(text.startIndex..., in: text)).map(\.range)
        }
        let string = text as NSString
        var ranges: [NSRange] = []
        for term in activeQuery.split(separator: " ") where string.length > 0 {
            var start = 0
            var found = 0
            while start < string.length, found < 2000 {   // 一个词出现几千次时不再往下列，够看了
                let range = string.range(of: String(term), options: [.caseInsensitive],
                                         range: NSRange(location: start, length: string.length - start))
                guard range.location != NSNotFound, range.length > 0 else { break }
                ranges.append(range)
                found += 1
                start = range.location + range.length
            }
        }
        return ranges
    }

    func previewAttributed(_ text: String, ranges: [NSRange]) -> NSAttributedString {
        let attributed = NSMutableAttributedString(string: text, attributes: [
            .font: previewText.font ?? .systemFont(ofSize: fontSize),
            .foregroundColor: NSColor.labelColor,
        ])
        for range in ranges where range.length > 0 && range.location + range.length <= attributed.length {
            attributed.addAttribute(.backgroundColor, value: NSColor.controlAccentColor.withAlphaComponent(0.30), range: range)
        }
        return attributed
    }

    /// 字符下标换成 UTF-16 的 NSRange（NSAttributedString 用的是 UTF-16），挨着的合成一段
    func utf16Ranges(_ positions: [Int], in text: String) -> [NSRange] {
        var offsets = [0]
        for character in text { offsets.append(offsets[offsets.count - 1] + String(character).utf16.count) }
        var ranges: [NSRange] = []
        for position in positions.sorted() where position + 1 < offsets.count {
            let range = NSRange(location: offsets[position], length: offsets[position + 1] - offsets[position])
            if let last = ranges.last, last.location + last.length == range.location {
                ranges[ranges.count - 1].length += range.length
            } else {
                ranges.append(range)
            }
        }
        return ranges
    }

    func appIcon(_ bundle: String?) -> NSImage? {
        guard let bundle else { return nil }
        if let icon = icons[bundle] { return icon }
        let icon = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundle).map { NSWorkspace.shared.icon(forFile: $0.path) }
        icons[bundle] = icon
        return icon
    }
