// 剪贴板历史（⌥⇧V）：
//   aero-helper clipboard-watch   常驻（yabairc 启动）：每 0.5 秒看一次剪贴板，变了就记一条：文字、图片、文件。
//                                 存在 ~/.config/fantastic-i3/clipboard/（history.json，图片在 images/，只有自己能读）。
//                                 密码管理器标成"隐藏 / 临时"的内容不记。最多 300 条，其中图片最多 40 张；
//                                 同样的内容再复制一次就挪到最上面。SIGHUP：重读（面板里删了条目）
//   aero-helper clipboard         面板（../../bin/fantastic-clipboard 打开，skhd 的 ⌥⇧V），样子和 ⌥⇥ 的列表一样
//                                 （系统弹出层材质、圆角、居中）：左边历史，右边预览选中的那条。直接打字搜索（汉字用拼音也行）；
//                                 ↑↓ 选，回车粘贴到当前应用（面板不抢前台，关掉后按一下 ⌘V），⌘回车 只复制，
//                                 ⌘⌫ 删掉这条，⌘+ / ⌘- 缩放（会记住），⌘0 恢复默认，Esc 或点面板外面关闭

import AppKit
import CryptoKit

let clipboardDir = NSString("~/.config/fantastic-i3/clipboard").expandingTildeInPath
let clipboardHistory = URL(fileURLWithPath: clipboardDir + "/history.json")
let clipboardImages = clipboardDir + "/images"
let clipboardMaxEntries = 300, clipboardMaxImages = 40

/// 密码管理器等标出的"别记"类型（nspasteboard.org 的约定）
let clipboardSkippedTypes: Set<String> = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
]

struct ClipEntry: Codable {
    var id: String
    var kind: String          // text / image / files
    var text: String?         // 文字；文件是路径，一行一个
    var image: String?        // 图片文件名（images/ 下）
    var size: String?         // 图片的像素尺寸
    var app: String?          // 复制时在最前面的应用
    var bundle: String?
    var date: Date
}

func loadClipHistory() -> [ClipEntry] {
    guard let data = try? Data(contentsOf: clipboardHistory) else { return [] }
    return (try? JSONDecoder().decode([ClipEntry].self, from: data)) ?? []
}

func saveClipHistory(_ entries: [ClipEntry]) {
    guard let data = try? JSONEncoder().encode(entries) else { return }
    try? data.write(to: clipboardHistory, options: .atomic)
    try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: clipboardHistory.path)
}

// MARK: - 记录

func watchClipboard() -> Never {
    let files = FileManager.default
    try? files.createDirectory(atPath: clipboardImages, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
    try? files.setAttributes([.posixPermissions: 0o700], ofItemAtPath: clipboardDir)
    var entries = loadClipHistory()
    let pasteboard = NSPasteboard.general
    var lastCount = pasteboard.changeCount

    signal(SIGHUP, SIG_IGN)
    let reload = DispatchSource.makeSignalSource(signal: SIGHUP, queue: .main)
    reload.setEventHandler { entries = loadClipHistory() }
    reload.resume()

    Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
        guard pasteboard.changeCount != lastCount else { return }
        lastCount = pasteboard.changeCount
        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard !types.isEmpty, types.isDisjoint(with: clipboardSkippedTypes) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        var entry = ClipEntry(id: UUID().uuidString, kind: "text", app: front?.localizedName,
                              bundle: front?.bundleIdentifier, date: Date())

        // 先看文件（访达里复制文件时也带着文件名文字和图标图片），再看文字（Office 复制文字时还附一张图），最后才是图片
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            entry.kind = "files"
            entry.text = urls.map(\.path).joined(separator: "\n")
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            entry.text = text.count > 200_000 ? String(text.prefix(200_000)) : text
        } else if let image = NSImage(pasteboard: pasteboard), let tiff = image.tiffRepresentation,
                  let bitmap = NSBitmapImageRep(data: tiff), let png = bitmap.representation(using: .png, properties: [:]),
                  png.count < 20_000_000 {
            let name = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined().prefix(24) + ".png"
            let path = clipboardImages + "/" + name
            if !files.fileExists(atPath: path) { try? png.write(to: URL(fileURLWithPath: path)) }
            entry.kind = "image"
            entry.image = String(name)
            entry.size = "\(bitmap.pixelsWide) × \(bitmap.pixelsHigh)"
        } else {
            return
        }

        // 同样的内容再复制一次：挪到最上面
        entries.removeAll { $0.kind == entry.kind && $0.text == entry.text && $0.image == entry.image }
        entries.insert(entry, at: 0)
        if entries.count > clipboardMaxEntries { entries.removeLast(entries.count - clipboardMaxEntries) }
        let images = entries.indices.filter { entries[$0].kind == "image" }
        if images.count > clipboardMaxImages {
            let drop = Set(images.dropFirst(clipboardMaxImages))
            entries = entries.indices.filter { !drop.contains($0) }.map { entries[$0] }
        }
        // 没人用的图片文件删掉
        let used = Set(entries.compactMap(\.image))
        for name in (try? files.contentsOfDirectory(atPath: clipboardImages)) ?? [] where !used.contains(name) {
            try? files.removeItem(atPath: clipboardImages + "/" + name)
        }
        saveClipHistory(entries)
    }
    withExtendedLifetime(reload) { RunLoop.main.run() }
    exit(0)
}

// MARK: - 面板

final class ClipboardPanel: NSObject, NSApplicationDelegate, NSWindowDelegate, NSTableViewDataSource, NSTableViewDelegate,
                            NSTextFieldDelegate {
    struct Row {
        let entry: ClipEntry
        let title: String
        let haystack: [[Character]]
    }

    /// 列表里标题的字号；其余尺寸都按它和默认值的比例缩放（⌘+ / ⌘- 调，会记住，⌘0 恢复默认）
    static let defaultFontSize: CGFloat = 13
    let store = UserDefaults(suiteName: "fantastic-i3.clipboard")!
    var fontSize: CGFloat
    var scale: CGFloat { fontSize / ClipboardPanel.defaultFontSize }

    var all: [Row] = []
    var shown: [Row] = []
    let panel = KeyPanel(contentRect: .zero, styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: false)
    let search = NSTextField()
    let divider = NSBox()
    let table = NSTableView()
    let scroll = NSScrollView()
    let split = NSBox()
    let previewText = NSTextView()
    let previewScroll = NSScrollView()
    let previewImage = NSImageView()
    let info = NSTextField(labelWithString: "")
    let hint = NSTextField(labelWithString: "↩ 粘贴    ⌘↩ 只复制    ⌘⌫ 删除    ⌘+ ⌘- 缩放    Esc 关闭")
    var screenFrame = NSRect.zero
    var center: NSPoint?
    var clickMonitor: Any?
    var icons: [String: NSImage] = [:]
    let fieldEditor: PlainFieldEditor = {
        let editor = PlainFieldEditor()
        editor.isFieldEditor = true
        return editor
    }()

    override init() {
        let saved = store.double(forKey: "fontSize")
        fontSize = saved > 0 ? CGFloat(saved) : ClipboardPanel.defaultFontSize
        super.init()
        all = loadClipHistory().map { entry in
            let text = entry.kind == "image" ? "图片 \(entry.size ?? "")" : (entry.text ?? "")
            let title = text.split(whereSeparator: \.isNewline).first.map(String.init)?
                .trimmingCharacters(in: .whitespaces) ?? ""
            return Row(entry: entry, title: title, haystack: searchKeys("\(text.prefix(300)) \(entry.app ?? "")"))
        }
        shown = all
    }

    func applicationDidFinishLaunching(_ notification: Notification) {
        // 和 ⌥⇥ 的窗口列表一样：系统弹出层材质，圆角用 maskImage（阴影也跟着圆角走）
        let radius: CGFloat = 16
        let mask = NSImage(size: NSSize(width: radius * 2 + 1, height: radius * 2 + 1), flipped: false) { rect in
            NSColor.black.setFill()
            NSBezierPath(roundedRect: rect, xRadius: radius, yRadius: radius).fill()
            return true
        }
        mask.capInsets = NSEdgeInsets(top: radius, left: radius, bottom: radius, right: radius)
        mask.resizingMode = .stretch
        let effect = NSVisualEffectView()
        effect.material = .popover
        effect.state = .active
        effect.blendingMode = .behindWindow
        effect.maskImage = mask

        // 不抢前台：原来的应用一直在前面，回车后关掉面板直接按 ⌘V 就粘到它里面
        panel.isFloatingPanel = true
        panel.level = .modalPanel
        panel.backgroundColor = .clear
        panel.isOpaque = false
        panel.hasShadow = true
        panel.becomesKeyOnlyIfNeeded = false
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
        panel.contentView = effect
        panel.delegate = self   // 给搜索框换上 PlainFieldEditor（按键不经过输入法）

        search.isBordered = false
        search.drawsBackground = false
        search.focusRingType = .none
        search.delegate = self
        search.cell?.usesSingleLineMode = true
        effect.addSubview(search)

        divider.boxType = .separator
        effect.addSubview(divider)

        let column = NSTableColumn(identifier: NSUserInterfaceItemIdentifier("entry"))
        table.addTableColumn(column)
        table.headerView = nil
        table.backgroundColor = .clear
        table.intercellSpacing = NSSize(width: 0, height: 2)
        table.style = .plain
        table.focusRingType = .none
        table.refusesFirstResponder = true
        table.dataSource = self
        table.delegate = self
        table.target = self
        table.action = #selector(clicked)
        table.doubleAction = #selector(doubleClicked)
        scroll.documentView = table
        scroll.drawsBackground = false
        scroll.hasVerticalScroller = true
        scroll.autohidesScrollers = true
        effect.addSubview(scroll)

        split.boxType = .separator
        effect.addSubview(split)

        // 右边预览：文字（能选中、能滚）或图片；下面一行是类型、大小、来源、时间
        previewText.isEditable = false
        previewText.isSelectable = true
        previewText.drawsBackground = false
        previewText.textColor = .labelColor
        previewText.textContainerInset = NSSize(width: 4, height: 6)
        previewText.isVerticallyResizable = true
        previewText.autoresizingMask = [.width]
        previewText.textContainer?.widthTracksTextView = true
        previewScroll.documentView = previewText
        previewScroll.drawsBackground = false
        previewScroll.hasVerticalScroller = true
        previewScroll.autohidesScrollers = true
        effect.addSubview(previewScroll)
        previewImage.imageScaling = .scaleProportionallyDown
        effect.addSubview(previewImage)
        info.textColor = .tertiaryLabelColor
        info.lineBreakMode = .byTruncatingTail
        effect.addSubview(info)

        hint.textColor = .tertiaryLabelColor
        hint.alignment = .center
        effect.addSubview(hint)

        // 放在鼠标那块屏的中间偏上（和窗口列表一样）
        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first { NSMouseInRect(mouse, $0.frame, false) } ?? NSScreen.main ?? NSScreen.screens[0]
        screenFrame = screen.visibleFrame

        NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
            guard let self, event.modifierFlags.contains(.command) else { return event }
            switch event.keyCode {
            case 36, 76: self.confirm(self.table.selectedRow, paste: false)          // ⌘↩ 只复制
            case 51: self.deleteSelected()                                            // ⌘⌫ 删掉这条
            case 24, 69: self.setFontSize(self.fontSize + 1)                          // ⌘= ⌘+（含小键盘）
            case 27, 78: self.setFontSize(self.fontSize - 1)                          // ⌘-
            case 29, 82: self.setFontSize(ClipboardPanel.defaultFontSize, save: false) // ⌘0 恢复默认
            case 12, 13: exit(0)                                                      // ⌘Q ⌘W
            default: return event
            }
            return nil
        }
        // 点面板外面就关（面板不抢前台，收不到"失去焦点"）
        clickMonitor = NSEvent.addGlobalMonitorForEvents(matching: [.leftMouseDown, .rightMouseDown]) { _ in exit(0) }

        layout()
        filter("")
        panel.makeKeyAndOrderFront(nil)
        panel.makeFirstResponder(search)
    }

    // 缩放

    func setFontSize(_ size: CGFloat, save: Bool = true) {
        fontSize = min(max(size, 9), 30)
        if save { store.set(Double(fontSize), forKey: "fontSize") } else { store.removeObject(forKey: "fontSize") }
        layout()
    }

    /// 按当前字号排版：窗口大小、字体、行高都跟着比例走；窗口中心不动，放不下时缩回屏幕里
    func layout() {
        let s = scale
        let pad = round(12 * s)
        let searchFont = round(20 * s), smallFont = max(9, round(11 * s))
        let searchHeight = ceil(searchFont * 1.5), hintHeight = ceil(smallFont * 2), infoHeight = ceil(smallFont * 1.8)
        let width = min(round(780 * s), floor(screenFrame.width * 0.95))
        let height = min(round(480 * s), floor(screenFrame.height * 0.9))
        let listWidth = round(width * 0.41)

        search.font = .systemFont(ofSize: searchFont)
        search.placeholderAttributedString = NSAttributedString(string: "搜索剪贴板…", attributes: [
            .font: NSFont.systemFont(ofSize: searchFont, weight: .light), .foregroundColor: NSColor.tertiaryLabelColor])
        previewText.font = .systemFont(ofSize: fontSize)
        info.font = .systemFont(ofSize: smallFont)
        hint.font = .systemFont(ofSize: smallFont)
        table.rowHeight = round(44 * s)

        let c = center ?? NSPoint(x: screenFrame.midX, y: screenFrame.midY + screenFrame.height * 0.08)
        center = c
        var frame = NSRect(x: round(c.x - width / 2), y: round(c.y - height / 2), width: width, height: height)
        frame.origin.x = min(max(frame.minX, screenFrame.minX), screenFrame.maxX - width)
        frame.origin.y = min(max(frame.minY, screenFrame.minY), screenFrame.maxY - height)
        panel.setFrame(frame, display: true)
        panel.invalidateShadow()   // 阴影跟着圆角重新计算

        search.frame = NSRect(x: pad + 6, y: height - pad - searchHeight, width: width - 2 * pad - 12, height: searchHeight)
        divider.frame = NSRect(x: pad, y: height - pad - searchHeight - pad / 2 - 1, width: width - 2 * pad, height: 1)
        let bodyTop = divider.frame.minY - pad / 2
        let bodyBottom = hintHeight + pad / 2
        scroll.frame = NSRect(x: pad / 2, y: bodyBottom, width: listWidth, height: bodyTop - bodyBottom)
        table.tableColumns.first?.width = scroll.contentSize.width
        split.frame = NSRect(x: scroll.frame.maxX + pad / 2, y: bodyBottom + 4, width: 1, height: bodyTop - bodyBottom - 8)
        let previewX = split.frame.maxX + pad
        let previewWidth = width - previewX - pad
        previewScroll.frame = NSRect(x: previewX, y: bodyBottom + infoHeight + 4, width: previewWidth,
                                     height: bodyTop - bodyBottom - infoHeight - 4)
        previewText.frame = NSRect(origin: .zero, size: previewScroll.contentSize)
        previewImage.frame = previewScroll.frame.insetBy(dx: 6, dy: 6)
        info.frame = NSRect(x: previewX + 4, y: bodyBottom, width: previewWidth - 8, height: infoHeight)
        hint.frame = NSRect(x: pad, y: 4, width: width - 2 * pad, height: hintHeight - 4)

        table.reloadData()   // 行按新的字号重画（选中的行不变）
        if shown.indices.contains(table.selectedRow) { table.scrollRowToVisible(table.selectedRow) }
    }

    func windowWillReturnFieldEditor(_ sender: NSWindow, to client: Any?) -> Any? {
        (client as? NSTextField) === search ? fieldEditor : nil
    }

    // 过滤、选择

    func filter(_ query: String) {
        let terms = query.lowercased().split(separator: " ").map(Array.init)
        if terms.isEmpty {
            shown = all
        } else {
            shown = all.enumerated().compactMap { index, row -> (Int, Int, Row)? in
                var total = 0
                for term in terms {
                    guard let score = row.haystack.compactMap({ fuzzyScore(term, $0) }).max() else { return nil }
                    total += score
                }
                return (total, index, row)
            }
            .sorted { $0.0 != $1.0 ? $0.0 > $1.0 : $0.1 < $1.1 }
            .map { $0.2 }
        }
        table.reloadData()
        select(0)
        if shown.isEmpty { showPreview(nil) }
    }

    func select(_ row: Int) {
        guard !shown.isEmpty else { return }
        let r = (row % shown.count + shown.count) % shown.count
        table.selectRowIndexes(IndexSet(integer: r), byExtendingSelection: false)
        table.scrollRowToVisible(r)
    }

    func tableViewSelectionDidChange(_ notification: Notification) {
        showPreview(shown.indices.contains(table.selectedRow) ? shown[table.selectedRow].entry : nil)
    }

    func showPreview(_ entry: ClipEntry?) {
        guard let entry else {
            previewText.string = all.isEmpty ? "剪贴板历史是空的：复制点东西再来" : "没有匹配的内容"
            previewText.textColor = .tertiaryLabelColor
            previewImage.image = nil
            previewImage.isHidden = true
            previewScroll.isHidden = false
            info.stringValue = ""
            return
        }
        var parts: [String] = []
        if entry.kind == "image", let name = entry.image {
            previewImage.image = NSImage(contentsOfFile: clipboardImages + "/" + name)
            previewImage.isHidden = false
            previewScroll.isHidden = true
            parts.append("图片 · \(entry.size ?? "")")
        } else {
            previewImage.isHidden = true
            previewScroll.isHidden = false
            previewText.string = entry.text ?? ""
            previewText.textColor = .labelColor
            previewText.scrollToBeginningOfDocument(nil)
            if entry.kind == "files" {
                let count = entry.text?.split(separator: "\n").count ?? 0
                parts.append("\(count) 个文件")
            } else {
                let text = entry.text ?? ""
                let lines = text.split(whereSeparator: \.isNewline).count
                parts.append("文字 · \(text.count) 字" + (lines > 1 ? " · \(lines) 行" : ""))
            }
        }
        if let app = entry.app { parts.append(app) }
        parts.append(timeText(entry.date))
        info.stringValue = parts.joined(separator: " · ")
    }

    func timeText(_ date: Date) -> String {
        let seconds = Date().timeIntervalSince(date)
        if seconds < 60 { return "刚刚" }
        if seconds < 3600 { return "\(Int(seconds / 60)) 分钟前" }
        let calendar = Calendar.current
        let formatter = DateFormatter()
        formatter.locale = Locale.current
        if calendar.isDateInToday(date) { formatter.dateFormat = "今天 HH:mm" }
        else if calendar.isDateInYesterday(date) { formatter.dateFormat = "昨天 HH:mm" }
        else { formatter.dateFormat = "M月d日 HH:mm" }
        return formatter.string(from: date)
    }

    // 粘贴、复制、删除

    /// 把这条放回剪贴板；paste 时关掉面板后按一下 ⌘V（面板没抢前台，粘到原来的应用里）
    func confirm(_ row: Int, paste: Bool = true) {
        guard shown.indices.contains(row) else { return }
        let entry = shown[row].entry
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.kind {
        case "image":
            if let name = entry.image, let image = NSImage(contentsOfFile: clipboardImages + "/" + name) {
                pasteboard.writeObjects([image])
            }
        case "files":
            let urls = (entry.text ?? "").split(separator: "\n").map { NSURL(fileURLWithPath: String($0)) }
            pasteboard.writeObjects(urls)
        default:
            pasteboard.setString(entry.text ?? "", forType: .string)
        }
        panel.orderOut(nil)
        guard paste else { exit(0) }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) {
            let source = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: down)   // V
                event?.flags = .maskCommand
                event?.post(tap: .cghidEventTap)
            }
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.1) { exit(0) }
        }
    }

    func deleteSelected() {
        let row = table.selectedRow
        guard shown.indices.contains(row) else { return }
        let id = shown[row].entry.id
        all.removeAll { $0.entry.id == id }
        shown.remove(at: row)
        saveClipHistory(all.map(\.entry))
        let reload = Process()   // 让记录的那个重读
        reload.executableURL = URL(fileURLWithPath: "/usr/bin/pkill")
        reload.arguments = ["-HUP", "-f", "^\(CommandLine.arguments[0]) clipboard-watch"]
        try? reload.run()
        table.reloadData()
        select(min(row, shown.count - 1))
        if shown.isEmpty { showPreview(nil) }
    }

    @objc func clicked() {
        if table.clickedRow >= 0 { select(table.clickedRow) }
    }

    @objc func doubleClicked() { confirm(table.clickedRow) }

    func controlTextDidChange(_ obj: Notification) { filter(search.stringValue) }

    func control(_ control: NSControl, textView: NSTextView, doCommandBy selector: Selector) -> Bool {
        switch selector {
        case #selector(NSResponder.moveDown(_:)), #selector(NSResponder.insertTab(_:)): select(table.selectedRow + 1)
        case #selector(NSResponder.moveUp(_:)), #selector(NSResponder.insertBacktab(_:)): select(table.selectedRow - 1)
        case #selector(NSResponder.insertNewline(_:)): confirm(table.selectedRow)
        case #selector(NSResponder.cancelOperation(_:)): exit(0)
        default: return false
        }
        return true
    }

    // 表格：一行是图标（来源应用的图标；图片是缩略图）、第一行内容、下面一行小字（来源 · 时间）

    func numberOfRows(in tableView: NSTableView) -> Int { shown.count }

    func tableView(_ tableView: NSTableView, rowViewForRow row: Int) -> NSTableRowView? { RowView() }

    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let entry = shown[row].entry
        let cell = NSTableCellView()
        let width = tableColumn?.width ?? scroll.contentSize.width
        let rowHeight = table.rowHeight
        let iconSize = round(28 * scale)
        let icon = NSImageView(frame: NSRect(x: round(10 * scale), y: (rowHeight - iconSize) / 2, width: iconSize, height: iconSize))
        icon.imageScaling = .scaleProportionallyUpOrDown
        if entry.kind == "image", let name = entry.image {
            icon.image = NSImage(contentsOfFile: clipboardImages + "/" + name)
        } else if entry.kind == "files", let first = entry.text?.split(separator: "\n").first {
            icon.image = NSWorkspace.shared.icon(forFile: String(first))
        } else {
            icon.image = appIcon(entry.bundle) ?? NSImage(systemSymbolName: "doc.text", accessibilityDescription: nil)
        }
        cell.addSubview(icon)

        let title = NSTextField(labelWithString: shown[row].title.isEmpty ? " " : shown[row].title)
        title.font = .systemFont(ofSize: fontSize, weight: .medium)
        title.lineBreakMode = .byTruncatingTail
        title.maximumNumberOfLines = 1
        let detail = NSTextField(labelWithString: [entry.app, timeText(entry.date)].compactMap { $0 }.joined(separator: " · "))
        detail.font = .systemFont(ofSize: max(9, round(11 * scale)))
        detail.textColor = .secondaryLabelColor
        detail.lineBreakMode = .byTruncatingTail
        // 两行字作为一块，在行里竖直居中
        let titleHeight = ceil(title.intrinsicContentSize.height), detailHeight = ceil(detail.intrinsicContentSize.height)
        let bottom = ((rowHeight - titleHeight - detailHeight) / 2).rounded()
        let x = icon.frame.maxX + round(10 * scale)
        title.frame = NSRect(x: x, y: bottom + detailHeight, width: width - x - 10, height: titleHeight)
        detail.frame = NSRect(x: x, y: bottom, width: width - x - 10, height: detailHeight)
        cell.addSubview(title)
        cell.addSubview(detail)
        return cell
    }

    func appIcon(_ bundle: String?) -> NSImage? {
        guard let bundle else { return nil }
        if let icon = icons[bundle] { return icon }
        let icon = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundle).map { NSWorkspace.shared.icon(forFile: $0.path) }
        icons[bundle] = icon
        return icon
    }
